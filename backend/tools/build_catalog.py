"""Build reproducible Korean university JSON and a C seed from official open data.
Uses the same public JSON download requests as the portal's Download JSON button.
No API key or user account is required. Curated changes are version controlled.
"""
import argparse
import collections
import hashlib
import json
import pathlib
import urllib.parse
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = 'https://www.data.go.kr/data/15107736/standard.do'

def download():
    with urllib.request.urlopen('https://www.data.go.kr/download/columList.json?pk=15107736&ext=JSON', timeout=45) as response:
        header = json.load(response)
    params = dict(publicDataPk='15107736', colNmList=header['tableVO']['colNmList'],
                  svcTableNm=header['tableVO']['svcTableNm'], totalCount=header['totalCount'], perPage=10000, page=1)
    if header['totalCount'] > 10000:
        raise ValueError('Source grew beyond one download page; update pagination before refreshing')
    url = 'https://www.data.go.kr/download/standard.json?' + urllib.parse.urlencode(params, doseq=True)
    with urllib.request.urlopen(url, timeout=45) as response:
        raw = response.read()
    if len(json.loads(raw)) != header['totalCount']:
        raise ValueError('Incomplete source download')
    return raw

def build(raw):
    rows = json.loads(raw)
    override = json.loads((ROOT / 'catalog/overrides.json').read_text(encoding='utf-8'))
    groups = collections.defaultdict(list)
    excluded = []
    for row in rows:
        if row['UNIV_SE_NM'] == '대학원':
            continue
        original = row['SCHL_NM'].strip()
        if original in override['excluded']:
            excluded.append({'name': original, 'reason': override['excluded'][original]})
            continue
        name = override['mergers'].get(original, original)
        groups[name].append(row)
    universities = []
    used_ids = set()
    for name, campuses in sorted(groups.items()):
        # Stable application ID, NOT an official school code. Names are never renumbered.
        identifier = 100000 + (int.from_bytes(hashlib.sha256(name.encode()).digest()[:4], 'big') & 0x3fffffff)
        if identifier in used_ids:
            raise ValueError('Stable ID collision: assign explicit IDs before publishing')
        used_ids.add(identifier)
        originals = sorted({r['SCHL_NM'] for r in campuses})
        primary = next((r for r in campuses if r['SCHL_NM'] == name and r['MAINBRANCH_NM'] == '본교'), campuses[0])
        universities.append(dict(id=identifier, name=name, kind=primary['SCHL_SE_NM'],
            regions=sorted({r['CTPV_NM'] for r in campuses}),
            aliases=[n for n in originals if n != name],
            campuses=[dict(source_name=r['SCHL_NM'], division=r['MAINBRANCH_NM'], region=r['CTPV_NM'],
                           address=r['LCTN_ROAD_NM_ADDR'], website=r['HMPG_ADDR']) for r in campuses]))
    metadata = dict(source=SOURCE, provider='한국대학교육협의회', reference_years=sorted({r['CRTR_YR'] for r in rows}),
        source_dates=sorted({r['CRTR_YMD'] for r in rows}), reviewed_at=override['reviewed_at'],
        changes_source=override['source'], source_sha256=hashlib.sha256(raw).hexdigest(),
        source_records=len(rows), count=len(universities),
        scope='학부 대학·전문대학·교육대학·방송통신·사이버·기능·기술대학. 대학원 단독 항목 제외. 동일 학교명 캠퍼스 합산, 공식 별도 분교 명칭 유지.',
        excluded=excluded)
    output = dict(metadata=metadata, universities=universities)
    (ROOT / 'catalog/universities.json').write_text(json.dumps(output, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    c = lambda value: json.dumps(value, ensure_ascii=True)
    # ASCII C escapes in \u form are standard C11 universal characters.
    lines = ['/* Generated by tools/build_catalog.py; do not renumber IDs. */',
             '#define CR_CATALOG_SOURCE_DATE ' + c(metadata['source_dates'][-1]),
             'static const CrCatalogEntry cr_catalog[] = {']
    for u in universities:
        values = [u['name'], u['kind']] + [json.dumps(u[k], ensure_ascii=False, separators=(',', ':')) for k in ('regions','aliases','campuses')]
        lines.append('    {' + str(u['id']) + ', ' + ', '.join(c(v) for v in values) + '},')
    lines += ['};', '']
    (ROOT / 'src/catalog_data.h').write_text('\n'.join(lines), encoding='ascii')
    print(f'Built {len(universities)} selectable university groups from {len(rows)} official rows.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--source', type=pathlib.Path, help='Previously downloaded official JSON; omit to refresh from portal')
    args = parser.parse_args()
    build(args.source.read_bytes() if args.source else download())
